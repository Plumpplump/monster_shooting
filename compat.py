"""macOS / OpenGL Core Profile compatibility shims for Ursina 8.3.0.

Three fixes are needed on macOS:

1. ``gl-version 3 2``: Panda3D otherwise opens a legacy OpenGL 2.1 context
   (GLSL 1.20).  None of Ursina's shaders can compile there and the game
   window renders garbage (quads stretched across the whole screen).
2. Bumping every shader source version up to 150: Ursina's bundled shaders
   declare ``#version 130``/``#version 140``, but Apple's OpenGL driver only
   accepts GLSL >= 150 in a Core Profile context and otherwise fails with
   "version '130' is not supported".
3. Replacing ``TransparencyAttrib.M_dual`` with ``M_alpha``: Apple's Core
   Profile driver does not blend ``M_dual`` quads at all (they render fully
   opaque).  Ursina applies ``M_dual`` to every model, so the full-screen
   ``camera.overlay`` (alpha 0) painted the entire window black.
4. Replacing the text shader's ``fwidth``-based SDF smoothing with direct
   coverage sampling: on this driver ``fwidth(dist)`` misbehaves and makes
   every glyph quad render fully opaque (solid blocks instead of letters).
   The font atlas already stores anti-aliased glyph coverage in the alpha
   channel, so it can be used directly.

``apply()`` must run after ``ursina`` is importable and *before* the
``Ursina`` app object is instantiated.  ``main.py`` calls it at the top.

``after_start()`` must be called once the ``Ursina`` app object exists:
Panda does not emit the ``aspectRatioChanged`` event on macOS at startup, so
the UI orthographic lens would keep its default 1x1 film size and the whole
UI would render at the wrong scale.
"""
import re

from panda3d.core import loadPrcFileData

VERSION_PATTERN = re.compile(r'#version\s+(\d+)')

# macOS Core Profile supports GLSL 150 - 410; every other platform accepts 150
# as well (the shaders this game uses are 130/140-style GLSL anyway).
MIN_VERSION, MAX_VERSION = 150, 410

# Replacement fragment for ursina's text shader (core-profile safe): the
# original computes `smoothstep(0.5 - fwidth(dist), 0.5 + fwidth(dist), dist)`
# to sharpen SDF-style edges, but this driver evaluates `fwidth` wrongly and
# the whole glyph quad ends up opaque.  The font atlas alpha already holds
# per-pixel coverage (antialiased), so sample it directly.
TEXT_FRAGMENT_FIXED = '''#version 150
uniform sampler2D p3d_Texture0;
in vec2 uvs;
out vec4 FINAL_COLOR;
in vec4 vertex_color;
void main() {
    float a = texture(p3d_Texture0, uvs).a;
    FINAL_COLOR = vec4(vertex_color.rgb, vertex_color.a * a);
}
'''


def _fix_shader_source(source):
    if not source:
        return source

    def _replace(match):
        version = int(match.group(1))
        version = max(MIN_VERSION, min(version, MAX_VERSION))
        return f'#version {version}'

    return VERSION_PATTERN.sub(_replace, source)


def _patch_transparency():
    """Ursina applies ``TransparencyAttrib.M_dual`` to every model; on this
    driver that mode does not blend at all (quads render opaque), which turns
    the alpha-0 full-screen ``camera.overlay`` into a black sheet over the
    whole window.  ``M_alpha`` blends correctly and looks identical on screen.
    """
    from panda3d.core import TransparencyAttrib
    from ursina.entity import Entity
    from ursina.scene import instance as scene

    def use_alpha(node_path):
        if (node_path is not None
                and node_path.getTransparency() == TransparencyAttrib.M_dual):
            node_path.setTransparency(TransparencyAttrib.M_alpha)

    # `Entity.model` is a property generated by `generate_properties_for_class`,
    # so patching `Entity.model_setter` would have no effect: wrap the property.
    original_setter = Entity.model.fset

    def model_setter(self, value):
        original_setter(self, value)
        use_alpha(getattr(self, '_model', None))

    Entity.model = property(Entity.model.fget, model_setter, Entity.model.fdel)

    # Entities created while `ursina` was imported (camera.overlay, ...) already
    # carry M_dual on their models: fix those up as well.
    from ursina import camera
    for entity in list(scene.entities):
        use_alpha(getattr(entity, '_model', None))
    use_alpha(getattr(getattr(camera, 'overlay', None), '_model', None))


def apply():
    """Make Panda3D/Ursina usable on macOS.  Safe to call on any platform."""
    loadPrcFileData('', 'gl-version 3 2')

    from ursina.shader import Shader, imported_shaders

    original_compile = Shader.compile

    def compile_with_fixed_versions(self, shader_includes=True):
        self.vertex = _fix_shader_source(self.vertex)
        self.fragment = _fix_shader_source(self.fragment)
        self.geometry = _fix_shader_source(self.geometry)
        return original_compile(self, shader_includes)

    Shader.compile = compile_with_fixed_versions

    # The text shader needs its fwidth-based smoothing replaced (fix 4 above);
    # do it before the recompile pass so the patched source is what gets
    # compiled.
    import ursina.entity
    import ursina.text
    ursina.text.text_shader.fragment = TEXT_FRAGMENT_FIXED
    ursina.text.text_shader.compiled = False
    ursina.text.text_shader.compile()

    # Recompile any shader that was already compiled during `import ursina`.
    # `imported_shaders` is keyed by name and `unlit_with_fog_shader` registers
    # itself under the name 'unlit_shader', so the dict alone is not enough:
    # collect the module-level shader objects explicitly as well.
    shaders = set(imported_shaders.values())
    shaders.update((
        ursina.entity.unlit_shader,
        ursina.entity.unlit_with_fog_shader,
        ursina.entity.Entity.default_shader,
        ursina.text.text_shader,
    ))
    for shader in shaders:
        if shader.compiled:
            shader.compiled = False
            shader.compile()

    # `camera.overlay` is created while `ursina` is being imported, so it still
    # holds a native shader compiled from the *old* source.  Re-assigning the
    # same (now fixed) shader wrapper replaces it.
    from ursina import camera
    overlay = getattr(camera, 'overlay', None)
    if overlay is not None and overlay._shader is not None:
        overlay.shader = overlay._shader

    _patch_transparency()


def after_start():
    """Call once after the ``Ursina`` app object exists (see main.py)."""
    from ursina import application, window
    if application.window_type == 'none':
        return
    window.update_aspect_ratio()
